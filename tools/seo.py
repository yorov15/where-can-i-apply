def esc(value):
    return html.escape(str(value or ""), quote=True)


def safe_url(value):
    if not isinstance(value, str):
        return None
    try:
        parsed = urlsplit(value)
        return value if parsed.scheme in ("http", "https") and parsed.hostname and not parsed.username and not parsed.password else None
    except ValueError:
        return None


def program_path(program):
    slug = program["id"]
    if not isinstance(slug, str) or not re.fullmatch(r"[a-z0-9][a-z0-9-]*", slug):
        raise ValueError("Unsafe program id")
    return f"programs/{slug}.html"


def json_ld(value):
    content = json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    digest = base64.b64encode(hashlib.sha256(content.encode()).digest()).decode()
    return f'<script type="application/ld+json">{content}</script>', f"'sha256-{digest}'"


def country_names(root):
    source = (root / "js" / "filter.js").read_text(encoding="utf-8")
    block = source.split("export const COUNTRY_RU = {", 1)[1].split("};", 1)[0]
    return dict(re.findall(r"([A-Z]{2}):\s*'([^']+)'", block))


