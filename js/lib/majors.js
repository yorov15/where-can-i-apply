// Направление обучения: редакторская разметка, которую ставит человек в
// data/programs/<id>.json (поле "majors"). Как и тип программы, она не
// берётся с сайта — с сайта берут требования.
//
// "any" значит «запись покрывает вуз целиком». Так размечены программы,
// где направление выбирается внутри вуза, а списков факультетов мы не
// собирали: поставить «медицина» без страницы-источника значило бы выдать
// догадку за проверенное.
//
// Список повторяет MAJORS в tools/schema.py; расхождение ловит тест.
export const MAJORS = ['cs', 'engineering', 'natural', 'business', 'social', 'humanities', 'arts', 'medicine', 'any'];

export const MAJOR_LABEL = {
  cs: 'Информатика и IT',
  engineering: 'Инженерия и техника',
  natural: 'Математика и естественные науки',
  business: 'Экономика и бизнес',
  social: 'Социальные науки и право',
  humanities: 'Гуманитарные науки и языки',
  arts: 'Искусство и дизайн',
  medicine: 'Медицина и здоровье',
  any: 'Любое направление',
};

// В анкете «любое направление» выбирать нечего: это признак записи, а не
// желание человека.
export const CHOSEN_MAJORS = MAJORS.filter((m) => m !== 'any');

// Незнакомое направление не подписывается выдумкой.
export const majorLabel = (key) => MAJOR_LABEL[key] ?? null;

// Названо ли направление у самой записи. «any» сюда не считается: запись,
// покрывающая вуз целиком, не назвала ничего, и поднимать её вверх за
// любое желание человека значило бы обещать то, чего мы не читали.
export function hasMajor(majors, wanted) {
  if (!wanted) return false;
  return (majors ?? []).includes(wanted);
}

// Запись покрывает вуз целиком — направление выбирается внутри.
export const coversAnyMajor = (majors) => (majors ?? []).includes('any');
